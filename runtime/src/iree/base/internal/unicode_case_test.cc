TEST(UnicodeCaseTest, FullUppercaseExpansions) {
  for (const auto& expected : kUppercaseExpansions) {
    SCOPED_TRACE(expected[0]);
    uint32_t actual[4] = {UINT32_MAX, UINT32_MAX, UINT32_MAX, UINT32_MAX};
    iree_host_size_t expected_count = expected[3] == 0 ? 2 : 3;
    ASSERT_EQ(iree_unicode_to_upper(expected[0], actual), expected_count);
    for (iree_host_size_t i = 0; i < expected_count; ++i) {
      EXPECT_EQ(actual[i], expected[i + 1]);
    }
    EXPECT_EQ(actual[expected_count], UINT32_MAX);
  }
}

TEST(UnicodeCaseTest, SupplementaryMappings) {
  EXPECT_EQ(to_upper_single(0x10428), 0x10400u);  // Deseret.
  EXPECT_EQ(to_upper_single(0x1E943), 0x1E921u);  // Adlam.
  EXPECT_EQ(to_lower_single(0x10400), 0x10428u);
  EXPECT_EQ(to_lower_single(0x1E921), 0x1E943u);
}

TEST(UnicodeCaseTest, UnmappedAndInvalidCodepoints) {
  for (uint32_t codepoint : {0u, 0xD800u, 0x10FFFFu, 0x110000u, UINT32_MAX}) {
    uint32_t actual[3] = {UINT32_MAX, UINT32_MAX, UINT32_MAX};
    EXPECT_EQ(iree_unicode_to_upper(codepoint, actual), 1u);
    EXPECT_EQ(actual[0], codepoint);
    EXPECT_EQ(actual[1], UINT32_MAX);
    EXPECT_EQ(to_lower_single(codepoint), codepoint);
  }
}

