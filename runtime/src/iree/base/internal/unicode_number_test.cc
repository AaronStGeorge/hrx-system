template <size_t N>
void ExpectPropertySet(bool (*predicate)(uint32_t),
                       const uint32_t (&ranges)[N][2], size_t expected_count) {
  size_t range_index = 0;
  size_t actual_count = 0;
  for (uint32_t codepoint = 0; codepoint <= IREE_UNICODE_MAX_CODEPOINT;
       ++codepoint) {
    while (range_index < N && codepoint > ranges[range_index][1]) {
      ++range_index;
    }
    bool expected = range_index < N && codepoint >= ranges[range_index][0];
    bool actual = predicate(codepoint);
    ASSERT_EQ(actual, expected) << "codepoint " << codepoint;
    actual_count += actual;
  }
  EXPECT_EQ(actual_count, expected_count);
  EXPECT_FALSE(predicate(IREE_UNICODE_MAX_CODEPOINT + 1));
  EXPECT_FALSE(predicate(UINT32_MAX));
}

TEST(UnicodeNumberTest, DecimalPropertySet) {
  ExpectPropertySet(iree_unicode_is_decimal, kDecimalRanges, 680);
}

TEST(UnicodeNumberTest, DigitPropertySet) {
  ExpectPropertySet(iree_unicode_is_digit, kDigitRanges, 808);
}

TEST(UnicodeNumberTest, DecimalDigitAndNumberAreDistinct) {
  EXPECT_TRUE(iree_unicode_is_decimal('5'));
  EXPECT_TRUE(iree_unicode_is_digit('5'));
  EXPECT_TRUE(iree_unicode_is_number('5'));

  EXPECT_FALSE(iree_unicode_is_decimal(0x00B2));  // Superscript two.
  EXPECT_TRUE(iree_unicode_is_digit(0x00B2));
  EXPECT_TRUE(iree_unicode_is_number(0x00B2));

  EXPECT_FALSE(iree_unicode_is_decimal(0x00BC));  // One quarter.
  EXPECT_FALSE(iree_unicode_is_digit(0x00BC));
  EXPECT_TRUE(iree_unicode_is_number(0x00BC));

  EXPECT_FALSE(iree_unicode_is_decimal(0x2167));  // Roman numeral eight.
  EXPECT_FALSE(iree_unicode_is_digit(0x2167));
  EXPECT_TRUE(iree_unicode_is_number(0x2167));
}

