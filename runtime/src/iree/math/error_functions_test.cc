template <typename Bits>
void ExpectErrorResult(Bits actual, Bits expected, bool exact) {
  if (exact || expected == 0) {
    EXPECT_EQ(actual, expected);
  } else {
    EXPECT_LE(actual > expected ? actual - expected : expected - actual,
              Bits{1});
  }
}

